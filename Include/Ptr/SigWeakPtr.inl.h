/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////
  
template <class T>
template <class Y> inline
SigWeakPtr<T>& SigWeakPtr<T>::operator=(const Ptr<Y>& ptr)
{
    Set(ptr.m_Object);
    return *this;
}

