///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void UARTDriver::Setup(const char* devicePath, UART::Channels channel)
{
    Ptr<UARDDriverInode> node = ptr_new<UARDDriverInode>(channel, this);
    Kernel::RegisterDevice(devicePath, node);
}

