///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

ssize_t UARTDriver::Write(Ptr<KFileNode> file, off64_t position, const void* buffer, size_t length)
{
    Ptr<UARDDriverInode> node = ptr_static_cast<UARDDriverInode>(file->GetInode());
    node->m_Port.Send(buffer, length);

    return length;
}

