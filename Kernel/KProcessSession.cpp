#include <Kernel/KProcessSession.h>
#include <Kernel/KProcessGroup.h>
#include <Kernel/KPIDNode.h>
#include <Kernel/VFS/KINode.h>

namespace kernel
{

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

KProcessSession::KProcessSession(pid_t id) : m_SessionID(id)
{
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

KProcessSession::~KProcessSession() = default;

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void KProcessSession::AddGroup(Ptr<KProcessGroup> group)
{
    kassert(gk_CurrentThread == nullptr || g_PIDMapMutex.IsLocked());
    kassert(group->GetSession() == this);

    m_Groups.push_back(group);
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void KProcessSession::RemoveGroup(Ptr<KProcessGroup> group)
{
    kassert(g_PIDMapMutex.IsLocked());
    kassert(group->GetSession() == this);

    if (group == m_ForegroundGroup) {
        m_ForegroundGroup = nullptr;
    }

    auto it = std::find(m_Groups.begin(), m_Groups.end(), group);
    if (kensure(it != m_Groups.end()))
    {
        m_Groups.erase(it);

        if (m_Groups.empty()) {
            kerase_pid_node_if_empty_pl(m_SessionID);
        }
    }
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void KProcessSession::SetForegroundGroup(Ptr<KProcessGroup> group) noexcept
{
    kassert(g_PIDMapMutex.IsLocked());
    kassert(group == nullptr || std::find(m_Groups.begin(), m_Groups.end(), group) != m_Groups.end());

    m_ForegroundGroup = group;
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

Ptr<KProcessGroup> KProcessSession::GetForegroundGroup() const noexcept
{
    kassert(g_PIDMapMutex.IsLocked());
    return m_ForegroundGroup;
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void KProcessSession::SetControllingTTY(Ptr<KInode> inode)
{
    kassert(g_PIDMapMutex.IsLocked());
    m_ControllingTTY = inode;
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

Ptr<KInode> KProcessSession::GetControllingTTY() const
{
    kassert(g_PIDMapMutex.IsLocked());
    return m_ControllingTTY;
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

const std::vector<Ptr<KProcessGroup>>& KProcessSession::GetGroupList() const noexcept
{
    kassert(g_PIDMapMutex.IsLocked());
    return m_Groups;
}

} // namespace kernel
