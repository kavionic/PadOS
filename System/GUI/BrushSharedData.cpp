///////////////////////////////////////////////////////////////////////////////

#include <cassert>

#include <App/Application.h>
#include <GUI/BrushSharedData.h>

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

PBrushSharedData::PBrushSharedData(PApplication* application, const PBrushData& data, const PImage& image)
    : m_Application(ptr_weak_cast(application)), m_Image(image), m_Data(data)
{
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

PApplication* PBrushSharedData::GetApplication() const
{
    return ptr_raw_pointer_cast(m_Application);
}

///////////////////////////////////////////////////////////////////////////////
/// \author Kurt Skauen
///////////////////////////////////////////////////////////////////////////////

void PBrushSharedData::SetProperties(const PBrushData& data, const PImage& image)
{
    assert(GetPtrCount() == 1);
    m_Data = data;
    m_Image = image;
}
